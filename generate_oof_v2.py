"""
generate_oof_v2.py
==================
Generates grouped out-of-fold predictions on the 483-row measured dataset.
Both model blocks use the same measured rows; the wider 2,696-row synthetic
dataset is intentionally excluded from headline evaluation.

The 3-feature baseline and frozen 11-feature model are written to the canonical
``oof_predictions_v2.csv`` store via ``common.oof_store.append_oof``.

Usage
-----
    python generate_oof_v2.py

Every run replaces the generated model/seed blocks, preventing stale scores
from surviving a change to the evaluation data or feature list.

Output
------
    oof_predictions_v2.csv   -- project root
"""

import argparse
import sys
from pathlib import Path

import pandas as pd
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.ensemble import RandomForestClassifier
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import roc_auc_score

try:
    from xgboost import XGBClassifier
    HAS_XGB = True
except ImportError:
    HAS_XGB = False
    print("WARNING: xgboost not installed – XGBoost rows will be skipped.")

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))

from common.cv_utils import oof_scores          # noqa: E402
from common.oof_store import OOF_CSV, append_oof, load_oof  # noqa: E402


# ---------------------------------------------------------------------------
# Model factories  (keep in sync with model_comparison.py / model_sweep_12features_final.py)
# ---------------------------------------------------------------------------

def _make_lr():
    return LogisticRegression(class_weight="balanced", random_state=42, max_iter=1000)


def _make_xgb_3feat():
    if not HAS_XGB:
        raise RuntimeError("xgboost not installed")
    return XGBClassifier(
        n_estimators=50, max_depth=3, learning_rate=0.1,
        random_state=42, eval_metric="logloss",
    )


def _make_rf():
    return RandomForestClassifier(
        n_estimators=50, max_depth=3, class_weight="balanced", random_state=42
    )


def _make_xgb_11feat():
    if not HAS_XGB:
        raise RuntimeError("xgboost not installed")
    return XGBClassifier(
        n_estimators=200, max_depth=3, learning_rate=0.1,
        eval_metric="logloss", random_state=42, n_jobs=-1,
    )


def _make_lr_11feat():
    return Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("scaler", StandardScaler()),
        ("clf", LogisticRegression(max_iter=2000, class_weight="balanced", random_state=42)),
    ])


def _make_rf_11feat():
    return Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("clf", RandomForestClassifier(
            n_estimators=300, max_depth=6, class_weight="balanced",
            random_state=42, n_jobs=-1,
        )),
    ])


# ---------------------------------------------------------------------------
# Feature column definitions
# ---------------------------------------------------------------------------

FEAT_3 = ["cosine_similarity", "entity_overlap", "length_ratio"]

FEAT_11 = [
    "cosine_similarity", "entity_overlap", "length_ratio", "sentence_count_ratio",
    "section_coverage", "verbatim_copy_rate", "trailing_specificity", "constraint_count",
    "role_pronoun_rate", "novel_api_rate", "function_name_preserved",
]

LEGACY_MODELS = {
    "LogisticRegression", "RandomForest", "XGBoost",
    "LogisticRegression_12feat", "RandomForest_12feat", "XGBoost_12feat",
}


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def _validate_dataset(df: pd.DataFrame) -> None:
    required = FEAT_3 + FEAT_11 + [
        "task_id", "corruption_type", "label", "source",
    ]
    missing = [column for column in required if column not in df.columns]
    if missing:
        raise ValueError(f"Measured feature dataset is missing columns: {missing}")
    if df.duplicated(["task_id", "corruption_type"]).any():
        raise ValueError("Measured feature dataset has duplicate task/corruption rows.")
    if not df["label"].isin([0, 1]).all() or df["label"].nunique() != 2:
        raise ValueError("Measured feature dataset must contain labels 0 and 1.")
    if df["task_id"].isna().any():
        raise ValueError("Measured feature dataset contains missing task IDs.")


def _remove_legacy_blocks() -> None:
    """Drop score blocks generated by the superseded 2,696/12-feature setup."""
    existing = load_oof()
    if existing.empty:
        return
    kept = existing[~existing["model"].isin(LEGACY_MODELS)]
    if len(kept) != len(existing):
        kept.to_csv(OOF_CSV, index=False)
        print(
            f"Removed {len(existing) - len(kept)} stale OOF rows "
            "from legacy model blocks."
        )


def _report_fold_overlaps(df: pd.DataFrame, n_splits: int = 5, seed: int = 0) -> None:
    from common.cv_utils import task_folds

    folds = task_folds(df, n_splits=n_splits, seed=seed)
    if len(folds) != len(df):
        raise RuntimeError("Fold assignments are not aligned to the feature rows.")
    groups = df["task_id"].to_numpy()
    print("Task overlap per fold:")
    for fold_id in range(n_splits):
        test = folds == fold_id
        train = ~test
        overlap = set(groups[train]) & set(groups[test])
        print(
            f"  fold {fold_id}: train_tasks={len(set(groups[train]))}, "
            f"test_tasks={len(set(groups[test]))}, overlap={len(overlap)}"
        )
        if overlap:
            raise RuntimeError(f"Task leakage in fold {fold_id}: {overlap}")


def main(overwrite: bool = True) -> None:
    print("=" * 70)
    print("generate_oof_v2.py  --  building oof_predictions_v2.csv")
    print("=" * 70)

    feat_csv = ROOT / "final_dataset_full_features.csv"
    if not feat_csv.exists():
        raise FileNotFoundError(f"Measured feature dataset not found: {feat_csv}")
    df = pd.read_csv(feat_csv)
    _validate_dataset(df)
    print(
        f"Measured data: {len(df)} rows, {df['task_id'].nunique()} tasks, "
        f"labels={df['label'].value_counts().sort_index().to_dict()}"
    )
    _report_fold_overlaps(df)
    _remove_legacy_blocks()

    # ------------------------------------------------------------------
    # Block A: 3-feature baselines from measured rows
    # ------------------------------------------------------------------
    print(f"\n[A] 3-feature models: {FEAT_3}")
    models_3feat = {
        "LogisticRegression_3feat": _make_lr,
        "RandomForest_3feat": _make_rf,
    }
    if HAS_XGB:
        models_3feat["XGBoost_3feat"] = _make_xgb_3feat

    for model_name, factory in models_3feat.items():
        print(f"  Running OOF for {model_name} (seed=0) …")
        scores = oof_scores(df, FEAT_3, factory, n_splits=5, seed=0)
        append_oof(df, scores, model=model_name, cv_seed=0, overwrite_existing=True)
        print(
            f"    AUROC={roc_auc_score(df['label'], scores):.6f}  "
            f"mean_score={scores.mean():.6f}"
        )

    # ------------------------------------------------------------------
    # Block B: frozen 11-feature models from the same measured rows
    # ------------------------------------------------------------------
    print(f"\n[B] Frozen 11-feature models: {FEAT_11}")
    models_11feat = {
        "LogisticRegression_11feat": _make_lr_11feat,
        "RandomForest_11feat": _make_rf_11feat,
    }
    if HAS_XGB:
        models_11feat["XGBoost_11feat"] = _make_xgb_11feat

    for model_name, factory in models_11feat.items():
        print(f"  Running OOF for {model_name} (seed=0) …")
        scores = oof_scores(df, FEAT_11, factory, n_splits=5, seed=0)
        append_oof(df, scores, model=model_name, cv_seed=0, overwrite_existing=True)
        print(
            f"    AUROC={roc_auc_score(df['label'], scores):.6f}  "
            f"mean_score={scores.mean():.6f}"
        )

    # ------------------------------------------------------------------
    # Summary
    # ------------------------------------------------------------------
    final = load_oof()
    if final.empty:
        print("\nERROR: oof_predictions_v2.csv is empty. Check that at least one "
              "input CSV exists.")
        sys.exit(1)

    print("\n" + "=" * 70)
    print("oof_predictions_v2.csv  --  summary")
    print("=" * 70)
    summary = (
        final.groupby(["model", "cv_seed"])
        .agg(n_rows=("score", "count"),
             n_tasks=("task_id", "nunique"),
             score_mean=("score", "mean"),
             score_std=("score", "std"))
        .reset_index()
    )
    print(summary.to_string(index=False))
    print(f"\nTotal rows: {len(final)}  |  File: {ROOT / 'oof_predictions_v2.csv'}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Build oof_predictions_v2.csv")
    parser.add_argument(
        "--overwrite", action="store_true",
        help="Accepted for compatibility; generated blocks are always replaced."
    )
    args = parser.parse_args()
    main(overwrite=args.overwrite)
